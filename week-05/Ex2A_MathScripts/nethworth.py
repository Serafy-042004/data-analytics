# Define asset values
bank_account = 5000.00
savings = 2000.00
car_value = 10000.00
cash = 500.00

# Define debt values
student_loan = 3000.00
credit_card = 1000.00
car_loan = 4000.00

# Calculate total assets
total_assets = bank_account + savings + car_value + cash

# Calculate total debts
total_debts = student_loan + credit_card + car_loan

# Calculate net worth
net_worth = total_assets - total_debts

# Display the results
print(f"Your total assets are {total_assets:.2f}")
print(f"Your total debts are {total_debts:.2f}")
print(f"Your net worth is {net_worth:.2f}")
